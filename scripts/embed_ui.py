#!/usr/bin/env python3
"""Compile the built interface into a C++ header the client links.

The page is part of the client, not content a server supplies, so it is
embedded rather than copied next to the DLL. A file on disk can be edited,
replaced or go missing; compiled in, it cannot.

Served at http://vanta/ui.html (and fw://vanta/ui.html). file:// is an
opaque origin: Chromium drops CEF process messages.

    python scripts/embed_ui.py
    python scripts/embed_ui.py ui/dist/index.html -o path/to/ui_content.hpp
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

def pick_source() -> Path:
    built = REPO / "ui" / "dist" / "index.html"
    if built.exists():
        return built
    return REPO / "data" / "ui" / "index.html"


def emit_header(data: bytes, source: Path, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "// <auto-generated>",
        f"//     Generated by scripts/embed_ui.py from {source.as_posix()}.",
        "//     DO NOT EDIT BY HAND - rebuild the interface instead.",
        "// </auto-generated>",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace VantaMP::UI::Generated {",
        "    // The interface, served at http://vanta/ui.html.",
        "    inline constexpr std::uint8_t kHtml[] = {",
    ]

    chunk = []
    for i, byte in enumerate(data):
        if i % 16 == 0 and chunk:
            lines.append("        " + "".join(chunk))
            chunk = []
        chunk.append(f"0x{byte:02x},")
    if chunk:
        lines.append("        " + "".join(chunk))

    lines.extend(
        [
            "    };",
            "",
            "    inline constexpr std::size_t kHtmlSize = sizeof(kHtml);",
            "} // namespace VantaMP::UI::Generated",
            "",
        ]
    )

    dest.write_text("\n".join(lines), encoding="utf-8")
    print(f"embedded {len(data):,} bytes into {dest}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", nargs="?", type=Path, help="built index.html (default: ui/dist, else data/ui)")
    parser.add_argument("-o", "--output", type=Path, help="generated header path")
    args = parser.parse_args()

    source = args.source.resolve() if args.source else pick_source()
    dest = args.output.resolve() if args.output else REPO / "code" / "client" / "src" / "core" / "ui" / "generated" / "ui_content.hpp"

    if not source.exists():
        print(f"error: {source} not found. Build the interface first (cd ui && npm run build).", file=sys.stderr)
        return 2

    emit_header(source.read_bytes(), source, dest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
