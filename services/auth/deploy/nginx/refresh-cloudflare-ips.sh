#!/bin/sh
# Fetch Cloudflare published proxy CIDRs and rewrite nginx real_ip config.
# Best-effort: failures keep the seeded / previous file. Safe while nginx is live.
set -eu

OUT="${CLOUDFLARE_REALIP_PATH:-/etc/nginx/dynamic/cloudflare-realip.conf}"
TMP="$(mktemp)"
V4_URL="${CLOUDFLARE_IPS_V4_URL:-https://www.cloudflare.com/ips-v4}"
V6_URL="${CLOUDFLARE_IPS_V6_URL:-https://www.cloudflare.com/ips-v6}"
# Keep short — Docker bridge egress on small VPS hosts often hangs.
TIMEOUT="${CLOUDFLARE_IPS_TIMEOUT:-5}"

fetch() {
  # busybox wget on alpine nginx image
  wget -qO- --timeout="$TIMEOUT" "$1" 2>/dev/null
}

# Avoid empty/partial writes when wget fails mid-pipeline.
set +e
{
  echo "# Auto-generated by refresh-cloudflare-ips.sh"
  echo "# Updated (UTC): $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# Sources: ${V4_URL} / ${V6_URL}"
  echo

  echo "# IPv4"
  fetch "$V4_URL" | while IFS= read -r cidr; do
    cidr="$(echo "$cidr" | tr -d '\r' | tr -d ' ')"
    [ -n "$cidr" ] || continue
    echo "set_real_ip_from ${cidr};"
  done

  echo
  echo "# IPv6"
  fetch "$V6_URL" | while IFS= read -r cidr; do
    cidr="$(echo "$cidr" | tr -d '\r' | tr -d ' ')"
    [ -n "$cidr" ] || continue
    echo "set_real_ip_from ${cidr};"
  done

  echo
  echo "real_ip_header CF-Connecting-IP;"
  echo "real_ip_recursive on;"
} >"$TMP"
set -e

count="$(grep -c '^set_real_ip_from ' "$TMP" || true)"
if [ "$count" -lt 10 ]; then
  echo "cloudflare-ips: refresh unreachable/incomplete (${count} ranges) — keeping previous file" >&2
  rm -f "$TMP"
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
if [ -f "$OUT" ] && cmp -s "$TMP" "$OUT"; then
  echo "cloudflare-ips: unchanged (${count} ranges)"
  rm -f "$TMP"
  exit 0
fi

mv "$TMP" "$OUT"
echo "cloudflare-ips: wrote ${OUT} (${count} ranges)"

if [ "${CLOUDFLARE_IPS_RELOAD:-1}" = "1" ] && [ -f /var/run/nginx.pid ]; then
  if nginx -t 2>/dev/null; then
    nginx -s reload
    echo "cloudflare-ips: nginx reloaded"
  else
    echo "cloudflare-ips: nginx -t failed — not reloading" >&2
    exit 1
  fi
fi
