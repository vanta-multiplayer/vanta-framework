#!/usr/bin/env bash
# Full wipe + regenerate secrets/certs + start the auth stack.
# Usage (from anywhere):
#   bash scripts/setup-fresh.sh --yes
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

if [[ "${1:-}" != "--yes" ]]; then
  cat <<'EOF'
This DESTROYS and recreates local auth state:
  - .env (new Postgres/Redis passwords)
  - deploy/nginx/certs/*.pem (new self-signed TLS)
  - Docker volumes: postgres + redis data
  - then: docker compose up -d --build

Run:
  bash scripts/setup-fresh.sh --yes
EOF
  exit 1
fi

export DOCKER_BUILDKIT=1

echo "==> stopping stack"
docker compose down --remove-orphans || true

echo "==> removing postgres/redis volumes"
while read -r vol; do
  [[ -n "$vol" ]] || continue
  echo "    rm $vol"
  docker volume rm -f "$vol" || true
done < <(docker volume ls -q | grep -E 'vanta_auth_(pg|redis)$' || true)

echo "==> removing .env + TLS certs"
rm -f .env
rm -f deploy/nginx/certs/fullchain.pem
rm -f deploy/nginx/certs/privkey.pem
# reset dynamic real_ip so nginx entrypoint re-seeds from the static seed file
rm -f deploy/nginx/dynamic/cloudflare-realip.conf
mkdir -p deploy/nginx/certs deploy/nginx/certbot deploy/nginx/dynamic deploy/nginx/letsencrypt

echo "==> generating secrets"
if command -v bun >/dev/null 2>&1; then
  bun run scripts/gen-secrets.ts --rotate
else
  # No bun on host — write .env with openssl/docker.
  PG_PASS="$(openssl rand -base64 32 2>/dev/null | tr '+/' '-_' | tr -d '=')" || \
    PG_PASS="$(docker run --rm alpine/openssl rand -base64 32 | tr '+/' '-_' | tr -d '=')"
  RD_PASS="$(openssl rand -base64 32 2>/dev/null | tr '+/' '-_' | tr -d '=')" || \
    RD_PASS="$(docker run --rm alpine/openssl rand -base64 32 | tr '+/' '-_' | tr -d '=')"
  cat >.env <<EOF
# Generated by scripts/setup-fresh.sh
# Do not commit this file.
# Postgres only reads POSTGRES_PASSWORD on first volume init.

VANTA_AUTH_PUBLIC_URL=https://id.vantamp.xyz
VANTA_AUTH_HOST=0.0.0.0
VANTA_AUTH_PORT=28080
POSTGRES_USER=vanta
POSTGRES_PASSWORD=${PG_PASS}
POSTGRES_DB=vanta_auth
DATABASE_URL=postgres://vanta:${PG_PASS}@127.0.0.1:5432/vanta_auth
REDIS_PASSWORD=${RD_PASS}
REDIS_URL=redis://:${RD_PASS}@127.0.0.1:6379/0
ACCESS_TOKEN_TTL_SECONDS=600
RATE_LIMIT_WINDOW_MS=60000
RATE_LIMIT_MAX_REGISTER=20
RATE_LIMIT_MAX_TOKEN=60
CERTBOT_EMAIL=admin@vantamp.xyz
CERTBOT_DOMAIN=id.vantamp.xyz
EOF
  echo "    wrote .env (no bun; openssl fallback)"
fi

echo "==> generating self-signed TLS certs"
if command -v bun >/dev/null 2>&1; then
  bun run scripts/gen-dev-certs.ts --force
else
  DOMAIN=id.vantamp.xyz
  docker run --rm -v "$ROOT/deploy/nginx/certs:/certs" alpine/openssl \
    req -x509 -nodes -newkey rsa:2048 -days 825 \
    -keyout /certs/privkey.pem -out /certs/fullchain.pem \
    -subj "/CN=${DOMAIN}" \
    -addext "subjectAltName=DNS:${DOMAIN},DNS:localhost,IP:127.0.0.1"
  echo "Self-signed cert for ${DOMAIN} (dev only)." >deploy/nginx/certs/README.txt
fi

echo "==> starting stack"
docker compose up -d --build

echo "==> waiting for auth health"
for i in $(seq 1 60); do
  if docker compose exec -T auth wget -q -O /dev/null http://127.0.0.1:28080/health 2>/dev/null; then
    echo "    auth healthy"
    break
  fi
  if [[ "$i" -eq 60 ]]; then
    echo "auth did not become healthy — check: docker compose logs auth"
    docker compose ps
    exit 1
  fi
  sleep 2
done

echo "==> smoke"
curl -sk --max-time 10 https://127.0.0.1/health -H 'Host: id.vantamp.xyz' || true
echo
echo "Done. Public: https://id.vantamp.xyz/health"
echo "When DNS + Cloudflare HTTP-01 are ready: bun run certs:http"
